#!/usr/bin/env node

const fs = require('node:fs/promises');
const path = require('node:path');

const USERNAME = process.env.GITHUB_USERNAME || 'saivivekvenna';
const TOKEN = process.env.GH_ACTIVITY_TOKEN || process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
const OUTPUT_FILE = path.resolve(__dirname, '..', 'github-activity-data.js');
const DAY_MS = 24 * 60 * 60 * 1000;
const LEVELS = {
    NONE: 0,
    FIRST_QUARTILE: 1,
    SECOND_QUARTILE: 2,
    THIRD_QUARTILE: 3,
    FOURTH_QUARTILE: 4,
};

function startOfUtcDay(date) {
    return new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()));
}

function addDays(date, days) {
    return new Date(date.getTime() + days * DAY_MS);
}

function dateKey(date) {
    return date.toISOString().slice(0, 10);
}

function buildDays(from, to) {
    const days = [];

    for (let cursor = new Date(from); cursor <= to; cursor = addDays(cursor, 1)) {
        days.push({ date: dateKey(cursor), count: 0, level: 0 });
    }

    return days;
}

async function githubGraphql(query, variables) {
    const response = await fetch('https://api.github.com/graphql', {
        method: 'POST',
        headers: {
            authorization: `Bearer ${TOKEN}`,
            'content-type': 'application/json',
            'user-agent': 'saivenna-com-github-activity',
        },
        body: JSON.stringify({ query, variables }),
    });

    const payload = await response.json();

    if (!response.ok || payload.errors) {
        const details = payload.errors ? JSON.stringify(payload.errors) : JSON.stringify(payload);
        throw new Error(`GitHub GraphQL request failed: ${response.status} ${details}`);
    }

    return payload.data;
}

async function fetchContributionActivity(username, from, to) {
    const query = `
        query GitHubContributionActivity($login: String!, $from: DateTime!, $to: DateTime!) {
            user(login: $login) {
                contributionsCollection(from: $from, to: $to) {
                    contributionCalendar {
                        totalContributions
                        weeks {
                            contributionDays {
                                contributionCount
                                contributionLevel
                                date
                            }
                        }
                    }
                }
            }
        }
    `;

    const data = await githubGraphql(query, {
        login: username,
        from: from.toISOString(),
        to: addDays(to, 1).toISOString(),
    });

    if (!data.user) {
        throw new Error(`GitHub user not found: ${username}`);
    }

    return data.user.contributionsCollection.contributionCalendar;
}

function normalizeCalendarDays(days, calendar) {
    const calendarDaysByDate = new Map();

    for (const week of calendar.weeks) {
        for (const day of week.contributionDays) {
            calendarDaysByDate.set(day.date, day);
        }
    }

    return days.map(day => {
        const calendarDay = calendarDaysByDate.get(day.date);

        if (!calendarDay) return day;

        return {
            date: day.date,
            count: calendarDay.contributionCount,
            level: LEVELS[calendarDay.contributionLevel] || 0,
        };
    });
}

function sumDays(days) {
    return days.reduce((total, day) => total + day.count, 0);
}

function normalizeTotal(calendar, days) {
    const total = Number(calendar.totalContributions) || 0;
    const dayTotal = sumDays(days);

    return total || dayTotal;
}

function serializeData(data) {
    return `// This file is generated by scripts/update-github-activity.js. Do not edit manually.
window.githubActivityData = ${JSON.stringify(data, null, 2)};
`;
}

async function main() {
    if (!TOKEN) {
        throw new Error('Set GH_ACTIVITY_TOKEN, GITHUB_TOKEN, or GH_TOKEN before running this script.');
    }

    const to = startOfUtcDay(new Date());
    const from = addDays(to, -364);
    const emptyDays = buildDays(from, to);
    const calendar = await fetchContributionActivity(USERNAME, from, to);
    const days = normalizeCalendarDays(emptyDays, calendar);

    const data = {
        username: USERNAME,
        generatedAt: new Date().toISOString(),
        from: dateKey(from),
        to: dateKey(to),
        totalContributions: normalizeTotal(calendar, days),
        days,
        source: 'github-contribution-calendar',
        includesPrivateWhenTokenAllows: true,
    };

    await fs.writeFile(OUTPUT_FILE, serializeData(data), 'utf8');
    console.log(`Wrote ${path.relative(process.cwd(), OUTPUT_FILE)} for ${USERNAME}`);
    console.log(`${data.totalContributions} contributions from ${data.from} to ${data.to}`);
}

main().catch(error => {
    console.error(error.message);
    process.exit(1);
});
